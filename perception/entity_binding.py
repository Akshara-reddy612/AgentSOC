"""
perception/entity_binding.py

Entity binding (Phase 2 step 2.7, 2026-10-10).

NCE reads only free-text evidence, which an attacker can write.  A hypothesis
can therefore name an account or host that the alert's structured telemetry
never mentions (e.g. an injected "svc_backup on server-db01" — entities that
DO exist in the knowledge graph, so SSE alone would find a path).  This module
compares each entity a hypothesis names with the alert's structured entity
fields (source_user, source_host, target_host, plus destination_ip /
destination_domain when a corpus provides them) and labels it:

    bound             equals the trusted field for the same role
    bound_other_role  equals a different trusted entity field (role swap)
    unknown           the hypothesis left it empty / "unknown"
    unverifiable      no trusted reference exists: the alert lacks that field,
                      or a T1071 external destination with no trusted
                      destination field (all current GUIDE corpora)
    unbound           names an entity the alert's trusted fields do not contain

Hypothesis summary (NCEHypothesis.entity_binding): "unbound" if any entity is
unbound, else "partial" if any is unknown/unverifiable, else "bound".  An
unbound hypothesis is routed to analyst review by the guardrail.

Trust assumption: the structured fields come from the sensor/SIEM, not from
free text.  In the current GUIDE corpora they are generated by the project's
converter, so this is a design-level check until Phase 3 / Experiment 3.
"""
from __future__ import annotations

import dataclasses
import re
from dataclasses import dataclass, field

from perception.nce_contract import NCEHypothesis
from perception.network_model import is_internal_address

BOUND = "bound"
BOUND_OTHER_ROLE = "bound_other_role"
UNKNOWN = "unknown"
UNVERIFIABLE = "unverifiable"
UNBOUND = "unbound"

_PLACEHOLDERS = {"", "unknown", "none", "n/a", "na", "null", "-", "?"}
_IPV4 = re.compile(r"^\d{1,3}(\.\d{1,3}){3}$")

# hypothesis attribute -> alert field for the same role
_ROLES = (("source_account", "source_user"),
          ("source_host", "source_host"),
          ("target_host", "target_host"))
_DESTINATION_FIELDS = ("destination_ip", "destination_domain")


def _norm_account(v: str) -> str:
    v = v.strip().lower()
    v = v.split("\\")[-1]          # DOMAIN\user
    return v.split("@")[0]         # user@domain


def _norm_host(v: str) -> str:
    v = v.strip().lower()
    if _IPV4.match(v):
        return v
    return v.split(".")[0] if v.endswith((".corp.local", ".local", ".internal")) else v


def _norm(attr: str, v: str) -> str:
    return _norm_account(v) if attr == "source_account" else _norm_host(v)


def _is_external(v: str) -> bool:
    v = v.strip().lower()
    if _IPV4.match(v):
        return not is_internal_address(v)
    return "." in v and not is_internal_address(v)


@dataclass(frozen=True)
class EntityBindingResult:
    roles: dict[str, str] = field(default_factory=dict)   # attr -> label
    summary: str = BOUND
    notes: list[str] = field(default_factory=list)


def bind_entities(hypothesis: NCEHypothesis, alert: dict) -> EntityBindingResult:
    """Label every entity the hypothesis names against the alert's structured fields."""
    trusted_accounts = {_norm_account(str(alert[f])) for f in ("source_user",)
                        if alert.get(f) and str(alert[f]).strip().lower() not in _PLACEHOLDERS}
    trusted_hosts = {_norm_host(str(alert[f])) for f in ("source_host", "target_host", *_DESTINATION_FIELDS)
                     if alert.get(f) and str(alert[f]).strip().lower() not in _PLACEHOLDERS}
    has_destination = any(alert.get(f) for f in _DESTINATION_FIELDS)

    roles: dict[str, str] = {}
    notes: list[str] = []
    for attr, alert_field in _ROLES:
        raw = str(getattr(hypothesis, attr) or "")
        if raw.strip().lower() in _PLACEHOLDERS:
            roles[attr] = UNKNOWN
            continue
        value = _norm(attr, raw)
        trusted = alert.get(alert_field)
        trusted_norm = _norm(attr, str(trusted)) if trusted and str(trusted).strip().lower() not in _PLACEHOLDERS else None
        if attr == "target_host" and hypothesis.technique_id == "T1071":
            # The C2 destination is checked against trusted destination fields only.
            if has_destination:
                dest = {_norm_host(str(alert[f])) for f in _DESTINATION_FIELDS if alert.get(f)}
                roles[attr] = BOUND if value in dest else UNBOUND
            elif value == trusted_norm:
                roles[attr] = BOUND
            elif _is_external(raw):
                roles[attr] = UNVERIFIABLE
            else:
                roles[attr] = UNBOUND
        elif value == trusted_norm:
            roles[attr] = BOUND
        elif value in (trusted_accounts if attr == "source_account" else trusted_hosts):
            roles[attr] = BOUND_OTHER_ROLE
        elif trusted_norm is None and not (trusted_accounts if attr == "source_account" else trusted_hosts):
            roles[attr] = UNVERIFIABLE
        else:
            roles[attr] = UNBOUND
        if roles[attr] == UNBOUND:
            notes.append(f"{attr}={raw!r} is not in the alert's structured entity fields")

    labels = set(roles.values())
    summary = "unbound" if UNBOUND in labels else ("partial" if labels & {UNKNOWN, UNVERIFIABLE} else "bound")
    return EntityBindingResult(roles=roles, summary=summary, notes=notes)


def label_entity_binding(hypotheses: list[NCEHypothesis], alert: dict) -> list[NCEHypothesis]:
    """Return new hypotheses with entity_binding set (order preserved)."""
    return [dataclasses.replace(h, entity_binding=bind_entities(h, alert).summary) for h in hypotheses]
